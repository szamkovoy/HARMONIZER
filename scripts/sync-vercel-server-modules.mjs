#!/usr/bin/env node
/**
 * Copy the minimal repo-root `modules/*` slice required by `_legacy_web` API routes
 * into `_legacy_web/modules/` for Vercel (Root Directory = _legacy_web).
 *
 * Run after changing server i18n sources:
 *   node scripts/sync-vercel-server-modules.mjs
 *
 * Only breath/day/practices typed overlays are vendored — not the full 8-language tree.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destRoot = path.join(repoRoot, "_legacy_web", "modules");

/** @type {Array<[string, string]>} [srcRelative, destRelative] */
const COPY_FILES = [
  ["modules/breath/i18n/coherence.ts", "breath/i18n/coherence.ts"],
  ["modules/breath/core/chakra.ts", "breath/core/chakra.ts"],
  ["modules/day/i18n/day.ts", "day/i18n/day.ts"],
  ["modules/life-spheres/labels.ts", "life-spheres/labels.ts"],
  ["modules/i18n/localeCodes.ts", "i18n/localeCodes.ts"],
  ["modules/i18n/typed/merge.ts", "i18n/typed/merge.ts"],
  ["modules/practices/i18n/practices.ts", "practices/i18n/practices.ts"],
  ["modules/practices/core/types.ts", "practices/core/types.ts"],
];

const OVERLAY_MODULES = ["breath", "day", "practices"];
const OVERLAY_LOCALES = ["de", "es", "fr", "it", "nl", "pt"];

function copyFile(srcRel, destRel) {
  const src = path.join(repoRoot, srcRel);
  const dest = path.join(destRoot, destRel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function copyOverlayCatalogs() {
  for (const moduleId of OVERLAY_MODULES) {
    for (const locale of OVERLAY_LOCALES) {
      copyFile(
        `modules/i18n/typed/catalog/${moduleId}/${locale}.json`,
        `i18n/typed/catalog/${moduleId}/${locale}.json`,
      );
    }
  }
}

function writeBreathIndex() {
  const dest = path.join(destRoot, "breath/index.ts");
  fs.writeFileSync(
    dest,
    `/** Server-side vendored entry — types only. Generated by scripts/sync-vercel-server-modules.mjs */
export type { BreathPracticeId, BreathLocale } from "@/modules/breath/i18n/coherence";
export type { Chakra } from "@/modules/breath/core/chakra";
`,
  );
}

function writeGeneratedOverlays() {
  const imports = OVERLAY_MODULES.flatMap((moduleId) =>
    OVERLAY_LOCALES.map(
      (locale) =>
        `import ${moduleId}_${locale} from "./catalog/${moduleId}/${locale}.json";`,
    ),
  );

  const blocks = OVERLAY_MODULES.map((moduleId) => {
    const entries = OVERLAY_LOCALES.map(
      (locale) => `    ${locale}: ${moduleId}_${locale} as Record<string, unknown>,`,
    ).join("\n");
    return `  ${moduleId}: {\n${entries}\n  },`;
  });

  const content = `/** AUTO-GENERATED by scripts/sync-vercel-server-modules.mjs — server API slice only. */
${imports.join("\n")}

export const GENERATED_TYPED_OVERLAYS: Record<
  string,
  Partial<Record<string, Record<string, unknown>>>
> = {
${blocks.join("\n")}
};
`;

  fs.writeFileSync(path.join(destRoot, "i18n/typed/generated-overlays.ts"), content);
}

function pruneExtraCatalogs() {
  const catalogRoot = path.join(destRoot, "i18n/typed/catalog");
  if (!fs.existsSync(catalogRoot)) return;
  for (const entry of fs.readdirSync(catalogRoot, { withFileTypes: true })) {
    if (entry.isDirectory() && !OVERLAY_MODULES.includes(entry.name)) {
      fs.rmSync(path.join(catalogRoot, entry.name), { recursive: true, force: true });
    }
  }
}

for (const [src, dest] of COPY_FILES) copyFile(src, dest);
copyOverlayCatalogs();
writeBreathIndex();
writeGeneratedOverlays();
pruneExtraCatalogs();

console.log(
  `[sync-vercel-server-modules] Updated _legacy_web/modules (${OVERLAY_MODULES.join(", ")} overlays only)`,
);
