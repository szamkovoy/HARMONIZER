SHORT_TEXT — КРАТКАЯ РЕКОМЕНДАЦИЯ (три полноценных абзаца)

Регистр: архетипический, юнгианский, с лёгким шлейфом сакрального, мистического понимания психики. Не гороскоп и не прогноз событий, а внутренний ориентир на день. Преврати сухую планету в живой объёмный архетип и объясни его через простые, узнаваемые жизненные проявления, сохранив прикосновение к тайне.

Веди единым текучим текстом (без списков и маркеров), кинестетично, чтобы отзывалось в теле и чувствах. Три полноценных абзаца, каждый 2–4 предложения:

Абзац 1 — Вход в день и архетип.
Опиши общее настроение дня языком состояний и представь Архетип главной планеты объёмным образом через понятную метафору. Дай почувствовать его характер и присутствие в обычной жизни. Планету и чакру пока НЕ называй.

Абзац 2 — Психологическая суть дня.
Как этот архетип проживается сегодня - с учётом коэффициента гармоничности главной планеты {{primary_harmoniousness}} (по шкале от -1.0 до +1.0; само число и шкалу в тексте не называй). Если он положительный - покажи, как гармоничные состояния главной планеты дают опору и возможность жить на позитивном ресурсе; если отрицательный - мягко коснись нескольких дисгармоничных состояний главной планеты как точки роста, которые в этот день можно трансформировать. Используй 3–5 состояний главной планеты, соединив их в живой текст; можно добавить тонкий обертон от второй или третьей планеты.

Абзац 3 — Практический фокус внимания.
Мягкое, жизненное приглашение: на что направить внимание, что разрешить себе, как действовать из этого архетипа в поведении, эмоциях и мыслях, чтобы прожить день эффективно и в согласии со своей природой. В конце можно один раз назвать чакру главной планеты, заметив что на неё полезно направить внимание в утренней практике йоги.

Тон рекомендательный, тёплый, поддерживающий: не «сегодня будет X», а «сегодня направьте внимание на X». Никакого фатализма и жёстких прогнозов. Если называешь чакру — только номерное название («вторая чакра»), без санскритских имён.

