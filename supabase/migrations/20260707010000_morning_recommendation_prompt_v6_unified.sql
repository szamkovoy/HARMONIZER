LONG_EXPLANATION — ПОДРОБНАЯ РЕКОМЕНДАЦИЯ (целевая длина ~{{long_explanation_target}} знаков)

Регистр: прагматичный, психологически-астрологический разбор. Здесь акцент НЕ на архетипы, а на традиционную астропсихологию: свойства и качества, связанные с планетами, характер аспектов между ними, как это переводится в психологические состояния в реальных жизненных ситуациях. Живой язык знатока дела, а не учебник. Ровно шесть смысловых блоков, каждый — с буквальным заголовком:

§1. ОБЩАЯ КАРТИНА ДНЯ
Какие три планеты сегодня формируют рисунок дня и почему именно они вышли на первый план. Опиши это понятным языком, без формул.

§2. ГЛАВНАЯ ТЕМА
Разбери планету {{primary_planet}} подробнее: какую психологическую тему она несёт сегодня и как её окрашивает транзит {{primary_main_transit}} {{primary_main_aspect}}. Ориентируйся на список состояний главной планеты, свойства транзитной планеты, и коэффициент гармоничности главной планеты {{primary_harmoniousness}} (шкала -1.0…+1.0, число в тексте не упоминай): при положительном — почему это ресурсный день для темы, опираясь на её гармоничные состояния; при отрицательном — почему это вызов с потенциалом роста, опираясь на дисгармоничные состояния и возможность их трансформации в положительные состояния.

§3. ВТОРАЯ ТЕМА
Как тема планеты {{secondary_planet}} сегодня дополняет тему главной планеты, смягчает или осложняет её — творчески опирайся на список состояний этой планеты и коэффициент её гармоничности, равный {{secondary_harmoniousness}} по шкале -1.0…+1.0. Данное число в тексте не упоминай.

§4. ТРЕТЬЯ ТЕМА
Что вносит в общую картину дня тема планеты {{tertiary_planet}} как третий обертон, с учётом её набора состояний и коэффициента гармоничности равного {{tertiary_harmoniousness}} по шкале -1.0…+1.0. Данное число в тексте не упоминай.

§5. КОНЦЕПТУАЛЬНАЯ ОПОРА
Короткий содержательный мостик к астрологической традиции (логика аспектов, Птолемей, Лилли, Порфирий и тому подобные авторитеты) — без перегруза, одной мысли достаточно.

§6. ЗАКЛЮЧЕНИЕ
Собери день в одну цельную глубокую мысль и заверши общей рекомендацией — на что направить внимание и как прожить этот день, чтобы он прошёл с максимальной пользой.

В подробной рекомендации не говори о чакрах (ни номерных, ни санскритских названий). Не повторяй одну и ту же планету как вторую и третью тему.

