SLOGAN (5–8 слов)

Это короткий авторский импульс, который схватывает нерв дня. Войди в образ архетипа — носителя лучших психологических состояний {{primary_planet}} — и сформулируй напутствие на этот день одним коротким предложением длиной 5–8 слов.

ПЛОХО:
- «Активна вторая чакра»
- «Сегодня важный день»
- «В этот день Венера гармонична»

ХОРОШО:
- литературно, образно, ёмко;
- понятно как руководство к действию;
- ощущается как живая фраза, а не тег.

