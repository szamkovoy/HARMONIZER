-- morning recommendation prompt v6 — fix neutral-tone (H≈0) handling.
--
-- Контекст: на скриншоте пользователя для дня Марса бейдж показывал «100% Марс»
-- без минуса (todayTone = "neutral", H_eff = 0), но LLM-текст рекомендации
-- говорил «Сегодня поток гармоничным не назвать...». Корневая причина — в
-- активном шаблоне v6 (он был обновлён напрямую в БД и разошёлся с файлом
-- миграции 20260707010000):
--
--   1. ОПЕЧАТКА в SHORT_TEXT абзац 2: обе ветки фразы-шаблона написаны как
--      «если коэффициент гармоничности положительный» — вторая должна быть
--      «отрицательный». Из-за этого LLM видит противоречивую инструкцию и для
--      нейтрального (H≈0) тона склоняется к дисгармоничной формулировке.
--   2. НЕТ случая «близко к нулю» в SHORT_TEXT: общий блок «КАК ЧИТАТЬ
--      КОЭФФИЦИЕНТ ГАРМОНИЧНОСТИ» упоминает «Около 0 — обе стороны присутствуют;
--      покажи выбор и баланс», но в конкретной инструкции по фразе-шаблону для
--      short_text нейтральный случай не описан — LLM не получает примера фразы.
--   3. НЕТ случая «близко к нулю» в §2 ГЛАВНАЯ ТЕМА (только положительный/
--      отрицательный).
--
-- Фикс: три точечных replace() в template для обоих активных ключей
-- (monologue_morning_recommendation и global_morning_recommendation, v6).
-- Версия не меняется (остаётся v6) — это исправление текста, не контракт.
--
-- ОТКАТ: вернуть template из миграции 20260707010000 (там исходный v6) или
-- применить обратный replace.

-- 1) monologue_morning_recommendation v6
