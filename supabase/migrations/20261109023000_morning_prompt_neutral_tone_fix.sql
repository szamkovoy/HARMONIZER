        $new_a$если коэффициент гармоничности положительный, отметь это например, как: "поток гармоничен и поддерживает, а значит..."; если коэффициент гармоничности отрицательный, отметь это фразой, подобной таким: "поток сегодня гармоничным не назвать, так что...", "поток дня не очень то гармоничен, поэтому..."; если коэффициент гармоничности близок к нулю, отметь это как смешанный, двойственный поток, например: "поток сегодня смешанный — есть и опора, и вызов...", "день держит обе стороны сразу, поэтому...". И далее если коэффициент гармоничности положительный - покажи,$new_a$
      ),
      -- (B) добавить нейтральный случай в «И далее»
      $old_b$если отрицательный - мягко коснись нескольких дисгармоничных состояний главной планеты как точки роста, которые в этот день можно трансформировать. Используй 3–5 состояний главной планеты, соединив их в живой текст.$old_b$,
      $new_b$если отрицательный - мягко коснись нескольких дисгармоничных состояний главной планеты как точки роста, которые в этот день можно трансформировать; если близок к нулю - сбалансированно покажи и гармоничные состояния как опору, и дисгармоничные как точку внимания, без перекоса в одну сторону. Используй 3–5 состояний главной планеты, соединив их в живой текст.$new_b$
    ),
    -- (C) добавить нейтральный случай в §2 ГЛАВНАЯ ТЕМА
    $old_c$при положительном — почему это ресурсный день для темы, опираясь на её гармоничные состояния; при отрицательном — почему это вызов с потенциалом роста, опираясь на дисгармоничные состояния и возможность их трансформации в положительные состояния.$old_c$,
    $new_c$при положительном — почему это ресурсный день для темы, опираясь на её гармоничные состояния; при отрицательном — почему это вызов с потенциалом роста, опираясь на дисгармоничные состояния и возможность их трансформации в положительные состояния; при близком к нулю — покажи обе стороны: и ресурс гармоничных состояний, и вызов дисгармоничных, как равноприсутствующие.$new_c$
  )
where prompt_key = 'monologue_morning_recommendation'
  and version = 6
  and is_active = true;

