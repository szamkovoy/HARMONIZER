- без перечисления планет и формул;
- без прямого копирования терминов из JSON;
- финал должен мягко вести к практике, а не звучать как приказ.

LONG_EXPLANATION: СТРУКТУРА

Это развёрнутый астропсихологический разбор. Здесь уже МОЖНО называть
